alter table public.wm_products
  add column if not exists photo_path_secondary text;

create table if not exists public.wm_personal_records (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references public.wm_tenants(id) on delete cascade,
  finance_scope text not null default 'store' check (finance_scope in ('store','personal')),
  entry_type text not null check (entry_type in ('sale_other_person','loan_given','loan_received','income','expense','payable','receivable')),
  person_name text,
  person_phone text,
  description text not null,
  category text not null default 'Outros',
  amount numeric(12,2) not null check (amount > 0),
  paid_amount numeric(12,2) not null default 0 check (paid_amount >= 0 and paid_amount <= amount),
  occurred_at date not null default current_date,
  due_date date,
  status text not null default 'open' check (status in ('open','partial','paid','overdue','canceled')),
  payment_method text,
  notes text,
  reminder_at timestamptz,
  reminder_sent_at timestamptz,
  attachments jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint wm_personal_records_paid_status_check check ((status <> 'paid') or paid_amount = amount)
);

create index if not exists wm_personal_records_tenant_scope_due_idx
  on public.wm_personal_records (tenant_id, finance_scope, status, due_date);
create index if not exists wm_personal_records_tenant_person_idx
  on public.wm_personal_records (tenant_id, lower(person_name));
alter table public.wm_personal_records enable row level security;